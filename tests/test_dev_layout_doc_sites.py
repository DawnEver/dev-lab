"""``doc_sites``: a NAMED doc builder's site ``output/docs/<site>/`` goes unjudged, its ``.js`` included.

A built documentation site (pdoc, ``cargo doc``) ships the JavaScript its pages run (search index, theme), so
``output/`` -- which never ALLOWS a code suffix in a row -- refused every built site. A site named in
``doc_sites`` of ``layout.toml`` is regenerated by its builder, so the scan leaves its tree unjudged, the
exemption symmetric to ``tool_caches`` and ``vendor_jobs``. An agent's own Write/Edit there is refused, naming the
builder as the door. PLANTED CONTROLS: an undeclared site and ``.js`` under any other output directory stay
refused, and a malformed entry reds at load.
"""

from __future__ import annotations

import re

import pytest

from dev_lab.dev._layout_table import LayoutNotDeclared, declared_layout
from dev_lab.dev.layout import layout_violations, refuse_layout
from tests.test_dev_layout import _HOMES, _checkout, _plant

_BODY = f"""doc_sites = ['pdoc', 'cargo-doc']
[layout]
{_HOMES}rust = ['.rs', '.toml']
'output/docs' = []
"""
_SITE_FILES = (
    'output/docs/pdoc/index.html',
    'output/docs/pdoc/search.js',
    'output/docs/pdoc/pkg/module.html',
    'output/docs/cargo-doc/static.files/main-1a2b.js',
    'output/docs/cargo-doc/crate/fn.solve.html',
)


def test_a_declared_doc_site_passes_the_scan_js_included(tmp_path) -> None:
    """PLANTED CONTROL: the same ``.js`` in an undeclared site is named."""
    root = _checkout(tmp_path, _BODY)
    for rel in _SITE_FILES:
        _plant(root, rel)
    assert layout_violations(root)[1] == []
    _plant(root, 'output/docs/sphinx/search.js')
    assert [line for line in layout_violations(root)[1] if 'output/docs/sphinx' in line] != []


def test_a_doc_site_is_only_the_output_docs_directory(tmp_path) -> None:
    """``pdoc/`` anywhere else is no site: ``output/cache/pdoc/x.js`` is still judged."""
    root = _checkout(tmp_path, _BODY.replace('[layout]\n', "[layout]\n'output/cache' = []\n"))
    _plant(root, 'output/cache/pdoc/x.js')
    assert [line for line in layout_violations(root)[1] if 'output/cache/pdoc' in line] != []


@pytest.mark.parametrize('entry', ['*', 'pd*', 'pdoc/sub', '../pdoc', ''])
def test_a_doc_sites_entry_that_is_not_one_named_site_is_refused(tmp_path, entry) -> None:
    root = _checkout(tmp_path, _BODY.replace("'cargo-doc'", f"'cargo-doc', {entry!r}"))
    with pytest.raises(LayoutNotDeclared, match='doc_sites'):
        declared_layout(root)


def test_doc_sites_that_is_not_a_list_is_refused(tmp_path) -> None:
    root = _checkout(tmp_path, re.sub(r'doc_sites = \[[^]]*\]', "doc_sites = 'pdoc'", _BODY))
    with pytest.raises(LayoutNotDeclared, match='doc_sites'):
        declared_layout(root)


def test_an_agent_never_hand_writes_a_doc_site(tmp_path) -> None:
    """The write hook refuses an agent's write into a declared site, naming the builder.

    PLANTED CONTROL: an undeclared site gives no builder door.
    """
    root = _checkout(tmp_path, _BODY)
    refusal = refuse_layout(root / 'output/docs/pdoc/index.html')
    assert refusal is not None
    assert 'doc_sites' in refusal
    assert 'builder' in refusal
    assert 'doc_sites' not in (refuse_layout(root / 'output/docs/sphinx/index.html') or '')
