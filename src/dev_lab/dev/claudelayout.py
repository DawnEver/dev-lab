"""THE CLOSED `.claude/` INVENTORY: every entry declared by name, `.claude/` only at the repo root.

User ruling 2026-11-24. Every entry is declared in :data:`CLAUDE_ENTRIES` -- the one list, as data.
Anything else is a stray:
a retired name is refused with its reason (:data:`RETIRED_CLAUDE_ENTRIES`, RETIRED-NAMES-REGISTERED), any other
with "undeclared". The family `.gitignore` section (``_famconfig_rows.GITIGNORE_CLAUDE_SECTION``) mirrors this
list so git cannot track a stray; this module is what refuses one on disk (:mod:`dev_lab.dev.famtests.claudelayout`).

Grammar of an entry: a literal relative path; ``<name>``/``<yyyy>``/``<mm>``/``<dd>`` one path segment of that
shape; ``*.md`` any markdown file name; a trailing ``/`` a directory whose contents are not inventoried.
"""

from __future__ import annotations

import os
import re
from typing import TYPE_CHECKING, Final

if TYPE_CHECKING:
    from pathlib import Path

__all__ = ['CLAUDE_DIR', 'CLAUDE_ENTRIES', 'RETIRED_CLAUDE_ENTRIES', 'stray_entries']

CLAUDE_DIR: Final = '.claude'

#: THE LIST (user ruling 2026-11-24): every entry `.claude/` may hold, with what it is.
CLAUDE_ENTRIES: Final[dict[str, str]] = {
    'settings.json': 'tracked; the agent settings (hook wiring, permissions)',
    'settings.local.json': 'machine-local, never rendered, never tracked',
    'automode.json': 'machine-local, generated by dev_lab.dev.automode from the fleet sources',
    'hooks/deny-commands.js': 'tracked; the agent guard engine (agent_guard install)',
    'hooks/venv_resolver.js': 'tracked; the one environment resolver (agent_guard install)',
    'hooks/py.js': 'tracked; the interpreter shim the hooks run through',
    'hooks/deny-rules.json': 'tracked; the deny registry plus the repo remedies (hook_adoption)',
    'hooks/native_session.json': 'tracked; stays JSON by declared exception, read by the agent JS',
    'memory/<yyyy>/<mm>/<dd>/*.md': 'tracked; one dated memory entry per file',
    'worktrees/<name>/': 'untracked; one lane checkout per directory (WORKTREES-STAY-INSIDE)',
}

#: RETIRED-NAMES-REGISTERED: what `.claude/` used to hold, refused by name with where it went.
RETIRED_CLAUDE_ENTRIES: Final[dict[str, str]] = {
    'rem.json': 'the backlog is the Gitea tasks repo plus the issue tracker',
    'sharp-review.json': 'the forge review is the one review (2026-11-05)',
    'tasks': 'task state lives in the Gitea tasks repo, never in a checkout',
    'rules': 'AGENTS.md is the one agent entry; the family section is rendered inside it',
    '.rem-state.json': 'rem keeps no per-checkout state',
    'memory-index.md': 'no derived memory index; memory is read by date',
}

_SEGMENT: Final = {'<name>': r'[^/]+', '<yyyy>': r'\d{4}', '<mm>': r'\d{2}', '<dd>': r'\d{2}'}

#: Directories a nested-`.claude` walk never enters: generated trees, environments and the root's own.
_PRUNE: Final = frozenset({'.git', '.venv', '.venvs', 'output', 'node_modules', 'target', '__pycache__'})


def _pattern(entry: str) -> re.Pattern[str]:
    parts = []
    for segment in entry.rstrip('/').split('/'):
        if segment in _SEGMENT:
            parts.append(_SEGMENT[segment])
        elif segment == '*.md':
            parts.append(r'[^/]+\.md')
        else:
            parts.append(re.escape(segment))
    tail = r'(?:/.*)?' if entry.endswith('/') else ''
    return re.compile('/'.join(parts) + tail)


_PATTERNS: Final = tuple(_pattern(entry) for entry in CLAUDE_ENTRIES)


def _why_stray(rel: str) -> str | None:
    if any(pattern.fullmatch(rel) for pattern in _PATTERNS):
        return None
    head = rel.split('/', 1)[0]
    if head in RETIRED_CLAUDE_ENTRIES:
        return f'RETIRED -- {RETIRED_CLAUDE_ENTRIES[head]}'
    return 'undeclared -- not in dev_lab.dev.claudelayout.CLAUDE_ENTRIES'


def _root_strays(root: Path) -> list[str]:
    base = root / CLAUDE_DIR
    files: list[str] = []
    for current, dirs, names in os.walk(base):
        here = os.path.relpath(current, base).replace(os.sep, '/')
        if here == 'worktrees':
            dirs.clear()  # each worktrees/<name>/ is a whole checkout: declared, never inventoried
        files += sorted(name if here == '.' else f'{here}/{name}' for name in names)
        dirs.sort()
    out: list[str] = []
    named: set[str] = set()
    for rel in sorted(files):
        why = _why_stray(rel)
        head = rel.split('/', 1)[0]
        if why is None or head in named:
            continue
        if head in RETIRED_CLAUDE_ENTRIES:
            named.add(head)  # a retired directory is named once, with its reason
        out.append(f'{CLAUDE_DIR}/{head if head in RETIRED_CLAUDE_ENTRIES else rel}: {why}')
    return out


def _nested(root: Path) -> list[str]:
    out: list[str] = []
    for current, dirs, _files in os.walk(root):
        here = os.path.relpath(current, root).replace(os.sep, '/')
        if here == '.':
            dirs[:] = [d for d in dirs if d not in _PRUNE and d != CLAUDE_DIR]
            continue
        if CLAUDE_DIR in dirs:
            out.append(f'{here}/{CLAUDE_DIR}: a .claude/ below the repo root -- only the root one exists')
        dirs[:] = [d for d in dirs if d not in _PRUNE and d != CLAUDE_DIR]
    return sorted(out)


def stray_entries(root: Path) -> tuple[str, ...]:
    """Every entry of *root*'s `.claude/` outside :data:`CLAUDE_ENTRIES`, and every `.claude/` below the root.

    One line per stray, ``"<path>: RETIRED -- <why>"`` or ``"<path>: undeclared -- ..."``; a retired directory
    is named once, not once per file in it. ``()`` is a closed tree.
    """
    return (*_root_strays(root), *_nested(root))
