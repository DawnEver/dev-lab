"""The deny registry rendered for Codex: ``prefix_rule(..., decision = "forbidden")``, and its declared gaps.

MEASURED 2026-11-16: Codex carried 0 of the registry's refusing rows, so every shape the Claude Code engine
refuses ran unjudged under Codex. Codex execpolicy matches an argv PREFIX (each position one token or a list of
alternatives), so a row renders only where its refused shapes share a prefix that no near-miss and no family door
starts with -- :mod:`tests.test_dev_codexdeny` holds both directions. Every other refusing row is a GAP with its
reason, stated in the rendered file too; a hint never refuses, so it is never forbidden.

The rows' regexes stay the one source of what is refused; this table is the prefix each one admits as a Codex
rule, checked against the row's own ``refuses`` and ``permits``. ``python -m dev_lab.dev.autodoors --write``
writes the file beside the doors file (:data:`dev_lab.dev.autodoors.CODEX_RULES_REL`).
"""

