"""THE PYTHON GENERATOR: one ``_ir_<module>.py`` per schema module, plus the shared runtime and codec.

Each record becomes a frozen slotted dataclass whose ``__post_init__`` is the runtime's validation, driven by the
record's generated field table (``_ir_fields``); the canonical JSON, the stored envelope and the import-time
freshness check are the runtime's too (:mod:`dev_lab.dev._ir_runtime`, copied verbatim). The format is
``docs-src/dev/ir-schema.md``. Every file written here is git-ignored and regenerated, never committed.
"""

from __future__ import annotations

import hashlib
from pathlib import Path
from typing import TYPE_CHECKING, Final

from dev_lab.dev import _ir_runtime

if TYPE_CHECKING:
    from dev_lab.dev.irmodel import IR, Field, Module, Record, TypeRef

__all__ = ['FINGERPRINT_PREFIX', 'expected_files', 'fingerprint', 'generator_version', 'render_module', 'write']

FINGERPRINT_PREFIX: Final = '# ir-schema-fingerprint: '
_HERE: Final = Path(__file__).parent
_TEMPLATES: Final = {name: _HERE / name for name in ('_ir_runtime.py', '_ir_codec.py')}
_GITIGNORE: Final = '# GENERATED by dev_lab.dev.irschema: the IR modules are regenerated, never committed.\n_ir_*.py\n'
_SCALAR_HINTS: Final = {'bool': 'bool', 'int': 'int', 'float': 'float', 'complex': 'complex', 'str': 'str'}


def generator_version() -> str:
    """A hash of the generator's own sources: any change to them makes every generated file stale."""
    digest = hashlib.sha256()
    for source in (Path(__file__), *_TEMPLATES.values()):
        digest.update(source.read_bytes().replace(b'\r\n', b'\n'))
    return digest.hexdigest()[:16]


def _sources(ir: IR, module: str) -> tuple[str, ...]:
    declaration = ir.declaration
    return (declaration.modules[module], declaration.quantities)


def fingerprint(ir: IR, module: str) -> str:
    """``<sources hash>:<generator version>`` of one generated module."""
    root = ir.declaration.root
    blobs = [(root / s).read_bytes() for s in _sources(ir, module)]
    return f'{_ir_runtime.sources_hash(ir.declaration.version_text, blobs)}:{generator_version()}'


def _alias(module: str) -> str:
    return f'_m_{module}'


def _ref(target: str, here: str, suffix: str = '') -> str:
    module, name = target.split('.')
    return f'{name}{suffix}' if module == here else f'{_alias(module)}.{name}{suffix}'


def _hint(f: Field, ref: TypeRef, here: str) -> str:
    kind = ref.kind
    if kind in _SCALAR_HINTS:
        return _SCALAR_HINTS[kind]
    if kind == 'array':
        return f'NDArray[np.{f.dtype}]'
    if kind == 'list':
        return f'tuple[{_hint(f, ref.item, here)}, ...]'
    return _ref(ref.target, here, 'Id' if kind == 'id' else '')


def _scalar_keys(ir: IR, f: Field) -> list[str]:
    parts = [f'dtype={f.dtype!r}', f'shape={f.shape!r}'] if f.dtype else []
    if f.quantity:
        quantity = ir.quantities[f.quantity]
        parts.append(f'unit={quantity.unit!r}')
        if quantity.db:
            parts.append(f'db={quantity.db!r}')
    for spelled, value in (('unique_by', f.unique_by), ('csr_values', f.csr_values), ('gauge', f.gauge_reference)):
        if value:
            parts.append(f'{spelled}={value!r}')
    return parts


def _spec(ir: IR, f: Field, ref: TypeRef, here: str, *, name: str) -> str:
    parts = [repr(name), repr(ref.kind)]
    if name and f.optional:
        parts.append('optional=True')
    if ref.kind in ('enum', 'record'):
        parts.append(f'target={_ref(ref.target, here)}')
    if ref.kind == 'list':
        parts.append(f'item={_spec(ir, f, ref.item, here, name="")}')
    if name:
        parts += _scalar_keys(ir, f)
    return f'F({", ".join(parts)})'


def _comment(ir: IR, f: Field) -> str:
    notes = [ir.quantities[f.quantity].unit] if f.quantity else []
    if f.shape:
        notes.append(f'shape {tuple(f.shape)!r}')
    if f.gauge_reference:
        notes.append(f'gauge at the boundary, relative to {f.gauge_reference}')
    return f'  # {"; ".join(notes)}' if notes else ''


def _record(ir: IR, record: Record) -> list[str]:
    here = record.module
    ordered = [f for f in record.fields if not f.optional] + [f for f in record.fields if f.optional]
    lines = ['', '', '@dataclass(frozen=True, slots=True, kw_only=True, eq=False)', f'class {record.name}:']
    lines.append(f'    """{record.doc or record.name}"""')
    lines.append('')
    for f in ordered:
        hint = _hint(f, f.type, here)
        default = ' | None = None' if f.optional else ''
        lines.append(f'    {f.name}: {hint}{default}{_comment(ir, f)}')
    lines += ['    _ir_dims: dict | None = _rt.ir_dims()', '', '    __post_init__ = _rt.post_init']
    return lines


def _table(ir: IR, module: Module, record: Record) -> list[str]:
    name = record.name
    specs = ''.join(f'\n    {_spec(ir, f, f.type, module.name, name=f.name)},' for f in record.fields)
    return [
        f'{name}._ir_name = {f"{module.name}.{name}"!r}',
        f'{name}._ir_version = VERSION',
        f'{name}._ir_bounds = _BOUNDS',
        f'{name}._ir_fields = ({specs}\n)',
        f'_rt.surface({name})',
    ]


def _imports(ir: IR, module: Module) -> list[str]:
    used = {
        ref.target.split('.')[0]
        for record in module.records.values()
        for f in record.fields
        for ref in (f.type, f.type.item)
        if ref is not None and ref.target
    } - {module.name}
    lines = []
    for other in sorted(used):
        if other in ir.declaration.external:
            lines.append(f'import {ir.declaration.external[other]} as {_alias(other)}')
        else:
            lines.append(f'from . import _ir_{other} as {_alias(other)}')
    return lines


def render_module(ir: IR, name: str) -> str:
    """The source of ``_ir_<name>.py``."""
    module = ir.modules[name]
    declaration = ir.declaration
    root_up = len(Path(declaration.package_dir).parts)
    sources = _sources(ir, name)
    lines = [
        f'{FINGERPRINT_PREFIX}{fingerprint(ir, name)}',
        f'"""GENERATED from {sources[0]} by dev_lab.dev.irschema; do not edit, never commit."""',
        '',
        '# ruff: noqa',
        'from __future__ import annotations',
        '',
        'from dataclasses import dataclass',
        'from enum import Enum',
        'from typing import NewType',
        '',
        'import numpy as np',
        'from numpy.typing import NDArray',
        '',
        'from . import _ir_runtime as _rt',
        'from ._ir_runtime import F',
        *_imports(ir, module),
        '',
        f'VERSION = {declaration.version_text!r}',
        f'SCHEMA_TOML = {module.source!r}',
        f'QUANTITIES_TOML = {ir.catalogue_source!r}',
        f'_BOUNDS = {module.dims!r}',
        f'_rt.check_fresh(__file__, {root_up}, "pyproject.toml", {sources!r}, {fingerprint(ir, name).split(":")[0]!r})',
        '',
    ]
    lines.extend(
        f'{record.name}Id = NewType({f"{record.name}Id"!r}, str)'
        for record in module.records.values()
        if any(f.name == 'id' and f.type.kind == 'id' for f in record.fields)
    )
    for enum in module.enums.values():
        lines += ['', '', f'class {enum.name}(Enum):', *(f'    {v} = {v!r}' for v in enum.values)]
    for record in module.records.values():
        lines += _record(ir, record)
    lines += ['', '']
    for record in module.records.values():
        lines += _table(ir, module, record)
    return '\n'.join(lines) + '\n'


def expected_files(ir: IR) -> dict[Path, str]:
    """Every generated file and its exact expected content (runtime first, then one module per schema)."""
    directory = ir.declaration.root / ir.declaration.package_dir
    header = f'{FINGERPRINT_PREFIX}runtime:{generator_version()}\n'
    files = {directory / name: header + source.read_text(encoding='utf-8') for name, source in _TEMPLATES.items()}
    files[directory / '.gitignore'] = _GITIGNORE
    for name in ir.modules:
        files[directory / f'_ir_{name}.py'] = render_module(ir, name)
    return files


def write(ir: IR) -> tuple[Path, ...]:
    """Write every generated file whose content differs; the paths written."""
    written = []
    for path, content in expected_files(ir).items():
        if not path.is_file() or path.read_text(encoding='utf-8') != content:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding='utf-8', newline='\n')
            written.append(path)
    return tuple(written)
